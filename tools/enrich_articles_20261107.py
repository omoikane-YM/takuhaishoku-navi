        m = re.search(r'\n\s*<section[^>]*id="recommended"', t) or re.search(r'\n\s*<section[^>]*id="faq"', t)
        assert m, slug
        t = t[: m.start() + 1] + build(a) + t[m.start() + 1 :]
        t = re.sub(r'(<li><a href="#recommended">)', lambda mm: TOC_LI + NL + "      " + mm.group(1), t, count=1)

def insert_before(text, marker, new, count=1):
    assert marker in text, marker
    return text.replace(marker, new + marker, count)


for cat, d in DATA.items():
    p = os.path.join(ROOT, cat, 'index.html')
    t = open(p, encoding='utf8').read()
    assert 'id="notes"' not in t, cat

    # 1. guide callout after hero
    if d['guide']:
        slug, label, blurb = d['guide']
        callout = f'''
  <div class="intro-block">
    <p><strong>選び方に迷ったら：</strong><a href="../guide/{slug}/">{label}</a>もあわせてご覧ください。{blurb}</p>
  </div>
'''
        m = re.search(r'(<section class="hero">.*?</section>\n)', t, re.S)
        t = t.replace(m.group(1), m.group(1) + callout, 1)

    # 2. notes + diagnosis before services
    notes_li = '\n'.join(f'      <li>{html.escape(x, quote=False)}</li>' for x in d['notes'])
    notes_more = ''
    if d['guide']:
        notes_more = f'\n    <p>くわしい解説は、<a href="../guide/{d["guide"][0]}/">{d["guide"][1]}</a>をご覧ください。</p>'
    notes_sec = f'''  <section class="intro-block" id="notes">
    <h2>{d['notes_h']}</h2>
    <ul>
{notes_li}
    </ul>{notes_more}
  </section>

  <section id="diagnosis">
    <h2>かんたん診断：あなたに合うのはどのタイプ？</h2>
    <div class="merit-demerit">
{chr(10).join('      ' + box(a, b) for a, b in d['diag'])}
    </div>
  </section>

'''
    t = insert_before(t, '  <section id="services">', notes_sec)

    # 3. TOC
    toc_new = '      <li><a href="#notes">' + d['notes_h'] + '</a></li>\n      <li><a href="#diagnosis">かんたん診断</a></li>\n'
    t = insert_before(t, '      <li><a href="#services">', toc_new)

    # 4. FAQ html (append before closing of faq section)
    faq_html = ''.join(f'''    <div class="intro-block">
      <h3>Q. {html.escape(q, quote=False)}</h3>
      <p>A. {html.escape(a, quote=False)}</p>
    </div>
''' for q, a in d['faq'])
    m = re.search(r'(<section id="faq">.*?)(  </section>)', t, re.S)
    t = t.replace(m.group(0), m.group(1) + faq_html + m.group(2), 1)

    # 5. FAQ JSON-LD
    def upd(mm):
        obj = json.loads(mm.group(1))
        if obj.get('@type') != 'FAQPage':
            return mm.group(0)
        for q, a in d['faq']:
            obj['mainEntity'].append({"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}})
        return '<script type="application/ld+json">\n' + json.dumps(obj, ensure_ascii=False, indent=2) + '\n</script>'
    t, n = re.subn(r'<script type="application/ld\+json">\s*(\{.*?\})\s*</script>', upd, t, flags=re.S)
    open(p, 'w', encoding='utf8', newline='\n').write(t)
    print('enhanced', cat)

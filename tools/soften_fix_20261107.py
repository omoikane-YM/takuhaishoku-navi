def main():
    applied = set()
    for f in FILES:
        t = f.read_text(encoding="utf-8")
        o = t
        for a, b in FIXES:
            if a in t:
                t = t.replace(a, b)
                applied.add(a)
        if t != o:
            f.write_text(t, encoding="utf-8", newline="\n")
    missing = [a for a, _ in FIXES if a not in applied]
    print("applied", len(applied), "missing", missing)
    for f in FILES:
        r = subprocess.run([sys.executable, str(f)], capture_output=True, text=True, encoding="utf-8")
        if r.returncode:
            print("ERR", f.name, r.stderr[-300:])
    print("rebuilt")


if __name__ == "__main__":
    main()
